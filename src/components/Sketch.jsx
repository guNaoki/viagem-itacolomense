// "c cx cy r" vira círculo; o resto é caminho
const Shape = ({ d, ...p }) => {
  if (d.startsWith('c ')) {
    const [cx, cy, r] = d.slice(2).split(' ').map(Number)
    return <circle cx={cx} cy={cy} r={r} {...p} />
  }
  return <path d={d} {...p} />
}

export default function Sketch({ art }) {
  const a = ART[art]
  if (!a) return null
  return (
    <svg className="sketch" viewBox="0 0 120 100" aria-hidden="true">
      {/* mancha de cor fora do registro, como numa impressão de risografia */}
      <g className="sketch__fill" transform="translate(4 3)">
        {a.fill.map(([c, d], i) => <Shape key={i} d={d} className={c} />)}
      </g>
      <g className="sketch__ink">
        {a.ink.map((d, i) => <Shape key={i} d={d} pathLength="1" />)}
      </g>
    </svg>
  )
}
